#!/usr/bin/env python3
"""vr_init.py -- scaffold a vr_analysis work folder anywhere.

Makes the pipeline usable off the original cluster: point it at any
nf-core/rnaseq `star_salmon` output directory and a reference GTF, and it
writes a complete, valid `config/project.yaml` plus the folder skeleton.

    python3 vr_init.py --dest ~/vr_run \\
        --trial trial1 --results /path/to/nfcore/results/star_salmon \\
        --gtf /path/to/genes.gtf

Sample metadata is DISCOVERED from the quant table's column names, then
written out for the user to correct -- cell_type in particular cannot be
inferred from a filename and must be checked by hand.

Usage:
  python3 vr_init.py --dest DIR --trial NAME --results DIR --gtf FILE
                     [--fasta FILE] [--platform NAME] [--force]
  python3 vr_init.py --dest DIR --add-trial NAME --results DIR
"""
from __future__ import annotations

import argparse
import os
import pathlib
import re
import sys

# Sample-name heuristics. These are GUESSES written into the config for the
# user to confirm -- never treated as established metadata.
_NONTARGET_HINTS = ("nontarget", "non_target", "non-target", "gfpneg", "gfp_neg", "negative")
_TARGET_HINTS = ("target", "gfppos", "gfp_pos", "positive", "pool")


def discover_samples(star_salmon: pathlib.Path) -> list[str]:
    """Read sample names from the merged gene-count table's header."""
    for name in ("salmon.merged.gene_counts.tsv", "salmon.merged.gene_tpm.tsv"):
        t = star_salmon / name
        if t.is_file():
            with open(t) as fh:
                header = fh.readline().rstrip("\n").split("\t")
            # first two columns are gene_id, gene_name
            return header[2:]
    raise SystemExit(
        f"no salmon.merged.gene_counts.tsv or gene_tpm.tsv under {star_salmon}\n"
        "  Is this really an nf-core/rnaseq star_salmon output directory?"
    )


def guess_cell_type(sample: str) -> str:
    s = sample.lower()
    if any(h in s for h in _NONTARGET_HINTS):
        return "nontarget"
    if any(h in s for h in _TARGET_HINTS):
        return "target"
    return "UNKNOWN"


def guess_n_cells(sample: str) -> str:
    m = re.search(r"(\d+)\s*cells?", sample, re.I)
    return m.group(1) if m else "null"


def sample_block(samples: list[str]) -> str:
    lines = []
    unknown = 0
    for s in samples:
        ct = guess_cell_type(s)
        if ct == "UNKNOWN":
            unknown += 1
        n = guess_n_cells(s)
        lines.append(
            f"    {s}: {{cell_type: {ct}, n_cells: {n}, prep_status: ok}}"
        )
    return "\n".join(lines), unknown


HEADER = """# vr_analysis config -- generated by vr_init.py
# EVERY threshold the pipeline uses lives here. Nothing is hardcoded in bin/.

project: {project}
work: {dest}

env:
  # Left blank deliberately: the driver detects conda / venv / Environment
  # Modules itself. Set VR_PYTHON to force a specific interpreter.
  activate: ""

reference:
  genome_key: {genome_key}
  gtf: {gtf}
  fasta: {fasta}
  # If your GTF has no `gene` feature rows, gene spans are aggregated from
  # transcript/exon rows automatically. Chromosome naming must match between
  # the GTF and the quant tables.

trials:
  {trial}:
    results: {results_parent}
    fastq: ""
    platform: {platform}

# ---------------------------------------------------------------------------
# CHECK THESE. cell_type cannot be inferred reliably from a sample name.
#   target    = the sorted population you want receptor calls from (e.g. GFP+)
#   nontarget = the negative control population (e.g. GFP-)
# n_cells is the number of cells pooled into the library; null if unknown.
# ---------------------------------------------------------------------------
samples:
  {trial}:
{sample_lines}

"""

# Blocks copied VERBATIM from the shipped template rather than retyped here.
# Rationale: an inline copy of `paths:`/`thresholds:`/`qc_thresholds:` silently
# drifts from what bin/ actually reads. When that happened during development,
# a hand-typed `thresholds:` block produced DIFFERENT VERDICTS on identical
# input -- the failure mode is wrong science, not a crash. The template is the
# single source of truth; this script only fills in site-specific fields.
_CARRIED_BLOCKS = ("paths", "markers", "thresholds", "qc_thresholds")


def template_path() -> pathlib.Path:
    """Locate config/project.template.yaml shipped beside this script."""
    here = pathlib.Path(__file__).resolve().parent
    for cand in (here / "../config/project.template.yaml",
                 here / "project.template.yaml",
                 here / "../project.template.yaml"):
        if cand.is_file():
            return cand.resolve()
    raise SystemExit(
        "cannot find config/project.template.yaml.\n"
        "  It ships alongside bin/ and carries the threshold, marker and path\n"
        "  blocks. Without it the generated config would need hand-typed\n"
        "  thresholds, which is exactly how verdicts drift."
    )


def carried_blocks() -> str:
    """Return the template's analysis blocks, verbatim, in template order."""
    text = template_path().read_text()
    # Split on top-level keys, keeping each block whole (comments included).
    parts = re.split(r"(?m)^(?=[a-z_]+:)", text)
    keep = []
    for part in parts:
        m = re.match(r"([a-z_]+):", part)
        if m and m.group(1) in _CARRIED_BLOCKS:
            keep.append(part.rstrip() + "\n")
    got = {re.match(r"([a-z_]+):", k).group(1) for k in keep}
    missing = set(_CARRIED_BLOCKS) - got
    if missing:
        raise SystemExit(
            f"template {template_path()} is missing required blocks: {sorted(missing)}"
        )
    return "\n".join(keep)


def main(argv=None):
    ap = argparse.ArgumentParser(description="scaffold a vr_analysis work folder")
    ap.add_argument("--dest", required=True, help="work folder to create")
    ap.add_argument("--trial", help="name for the first trial (e.g. trial1)")
    ap.add_argument("--add-trial", help="add a trial to an existing config")
    ap.add_argument("--results", required=True,
                    help="nf-core/rnaseq star_salmon directory, or its parent")
    ap.add_argument("--gtf", help="reference GTF used for the quantification")
    ap.add_argument("--fasta", default="", help="reference FASTA (optional)")
    ap.add_argument("--genome-key", default="unspecified",
                    help="label for the reference, recorded for provenance")
    ap.add_argument("--platform", default="Illumina")
    ap.add_argument("--project", default="VNO receptor RNA-seq")
    ap.add_argument("--force", action="store_true",
                    help="overwrite an existing config")
    args = ap.parse_args(argv)

    trial = args.add_trial or args.trial
    if not trial:
        raise SystemExit("give --trial NAME (new config) or --add-trial NAME")

    res = pathlib.Path(os.path.abspath(os.path.expanduser(args.results)))
    # Accept either the star_salmon dir itself or the run root above it.
    if res.name == "star_salmon":
        star_salmon, results_parent = res, res.parent
    elif (res / "star_salmon").is_dir():
        star_salmon, results_parent = res / "star_salmon", res
    else:
        raise SystemExit(
            f"{res} is neither a star_salmon directory nor a run root containing one"
        )

    samples = discover_samples(star_salmon)
    sample_lines, unknown = sample_block(samples)

    dest = pathlib.Path(os.path.abspath(os.path.expanduser(args.dest)))
    cfg_path = dest / "config" / "project.yaml"

    if args.add_trial:
        if not cfg_path.is_file():
            raise SystemExit(f"no config at {cfg_path}; run without --add-trial first")
        s = cfg_path.read_text()
        if f"\n  {trial}:" in s:
            raise SystemExit(f"trial {trial!r} is already in {cfg_path}")
        # Insert INSIDE the existing blocks -- a naive append would create a
        # second top-level key, which YAML resolves last-wins with no error.
        s = s.replace(
            "\ntrials:\n",
            f"\ntrials:\n  {trial}:\n    results: {results_parent}\n"
            f"    fastq: \"\"\n    platform: {args.platform}\n",
            1,
        )
        s = s.replace("\nsamples:\n", f"\nsamples:\n  {trial}:\n{sample_lines}\n", 1)
        cfg_path.write_text(s)
        print(f"added trial {trial!r} with {len(samples)} samples to {cfg_path}")
    else:
        if cfg_path.is_file() and not args.force:
            raise SystemExit(f"{cfg_path} exists; pass --force to overwrite")
        if not args.gtf:
            raise SystemExit("--gtf is required when creating a new config")
        for sub in ("bin", "config", "ref", "results", "docs", "logs"):
            (dest / sub).mkdir(parents=True, exist_ok=True)
        cfg_path.write_text(HEADER.format(
            project=args.project,
            dest=dest,
            genome_key=args.genome_key,
            gtf=os.path.abspath(os.path.expanduser(args.gtf)),
            fasta=os.path.abspath(os.path.expanduser(args.fasta)) if args.fasta else '""',
            trial=trial,
            results_parent=results_parent,
            platform=args.platform,
            sample_lines=sample_lines,
        ) + carried_blocks())
        print(f"wrote {cfg_path}")
        print(f"scaffolded {dest}/{{bin,config,ref,results,docs,logs}}")

    # Verify what we wrote is actually loadable by the pipeline's own config
    # module -- not merely valid YAML. A template with a mistyped `paths:` key
    # parses fine and then dies with a KeyError several stages in, so validate
    # against the real contract here, at init time, where the fix is cheap.
    try:
        import yaml
    except ImportError:
        print("(pyyaml not importable here -- config written but NOT validated)")
        return 0

    text = cfg_path.read_text()
    d = yaml.safe_load(text)
    keys = re.findall(r"(?m)^([a-z_]+):", text)
    dupes = {k for k in keys if keys.count(k) > 1}
    if dupes:
        raise SystemExit(f"BUG: duplicate top-level keys written: {sorted(dupes)}")
    if trial not in (d.get("samples") or {}):
        raise SystemExit(f"BUG: trial {trial!r} missing from samples block")

    # Cross-check against bin/vr_config.py if it is importable, so the contract
    # is read from the code rather than restated here.
    required_paths = {"gene_counts", "gene_tpm", "tx2gene", "star_logs",
                      "qualimap", "multiqc_data", "per_sample_salmon"}
    got = set((d.get("paths") or {}))
    missing = required_paths - got
    if missing:
        raise SystemExit(
            f"BUG: config `paths:` is missing required keys: {sorted(missing)}\n"
            "  These are indexed by name in bin/ and cannot be renamed."
        )
    sys.path.insert(0, str(dest / "bin"))
    try:
        import vr_config  # noqa: F401  (present only once bin/ is populated)
        cfg = vr_config.load_config(str(cfg_path))
        P = vr_config.trial_paths(cfg, trial)
        vr_config.samples_of(cfg, trial)
        print(f"config validated by vr_config: {len(P)} resolved paths for {trial!r}")
        absent = [k for k in ("gene_counts", "star_logs") if not os.path.exists(P[k])]
        if absent:
            print(f"  NOTE: these resolved paths do not exist yet: {absent}")
            print("        check trials.%s.results points at the run ROOT" % trial)
    except ImportError:
        print(f"config parses; {len(keys)} unique top-level keys "
              "(copy bin/ in to also validate against vr_config)")

    print(f"\ndiscovered {len(samples)} samples: {', '.join(samples)}")
    if unknown:
        print(f"\n  !! {unknown} sample(s) have cell_type: UNKNOWN.")
        print("     Edit them to 'target' or 'nontarget' before running --")
        print("     the sort-validation tier cannot interpret UNKNOWN.")
    print("\nnext:")
    print(f"  cp -r <pipeline>/bin/* {dest}/bin/     # if bin/ is not already there")
    print(f"  cd {dest} && bin/run_pipeline.sh --trial {trial} --finalize")
    return 0


if __name__ == "__main__":
    sys.exit(main())
